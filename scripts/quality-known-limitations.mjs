#!/usr/bin/env node
// Writes docs/quality/KNOWN_LIMITATIONS.md from review-findings.json, so every document that lists
// limitations reads one source (review 2026-10-14). `--check` fails when the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const root = new URL("../", import.meta.url);
const registerUrl = new URL("docs/quality/review-findings.json", root);
const outputUrl = new URL("docs/quality/KNOWN_LIMITATIONS.md", root);
const sections = [
  ["open", "Open", "Confirmed and not fixed yet."],
  ["partial", "Partly fixed", "The code change is in; the evidence named in the disposition is still missing."],
  ["accepted-tradeoff", "Accepted trade-offs", "Known and kept, for the reason given."],
  ["product-decision", "Product decisions", "Scope choices, not defects."]
];

export function renderKnownLimitations(register) {
  const findings = register.findings;
  const counts = Object.fromEntries(["fixed", "not-a-defect", ...sections.map(([key]) => key)].map((key) => [key, findings.filter((f) => f.resolution === key).length]));
  const lines = [
    "# Known limitations",
    "",
    "Generated by `node scripts/quality-known-limitations.mjs` from `review-findings.json`; do not edit by hand.",
    `Of ${findings.length} findings, ${counts.fixed} are fixed and ${counts["not-a-defect"]} were not defects. The rest are listed here.`,
    ""
  ];
  for (const [key, title, description] of sections) {
    const items = findings.filter((f) => f.resolution === key);
    lines.push(`## ${title} (${items.length})`, "", description, "");
    for (const f of items) lines.push(`- **${f.id}** (${f.severity}) ${f.observation.trim()}. ${String(f.disposition ?? "").replace(/\s+/g, " ").trim()}`);
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const text = renderKnownLimitations(JSON.parse(readFileSync(registerUrl, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(outputUrl, "utf8") !== text) {
      process.stderr.write("docs/quality/KNOWN_LIMITATIONS.md is out of date: run node scripts/quality-known-limitations.mjs\n");
      process.exitCode = 1;
    }
  } else {
    writeFileSync(outputUrl, text);
  }
}
