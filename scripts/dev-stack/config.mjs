const secretSpecs = [
  ["postgresPassword", 32],
  ["sessionSecret", 48],
  ["setupToken", 32]
];

/** Creates missing secrets (0600 in a 0700 directory) and returns all of them. Existing ones are kept. */
export async function ensureSecrets(paths) {
  await mkdir(paths.secrets, { recursive: true, mode: 0o700 });
  await chmod(paths.secrets, 0o700);
  const secrets = {};
  for (const [key, bytes] of secretSpecs) {
    const path = paths[key];
    let value;
    try {
      value = (await readFile(path, "utf8")).trim();
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    if (!value) {
      value = randomBytes(bytes).toString("base64url");
      await writeFile(path, `${value}\n`, { mode: 0o600 });
    }
    await chmod(path, 0o600);
    secrets[key] = value;
  }
  return secrets;
}

