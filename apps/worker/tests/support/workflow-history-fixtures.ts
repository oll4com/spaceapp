import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import proto from "@temporalio/proto";
import type { CapturedHistory } from "./temporal-test-harness.js";

const { temporal } = proto;

export const fixtureDirectory = fileURLToPath(new URL("../fixtures/workflow-histories/", import.meta.url));
export const workflowTypes = [
  "dotGoalWorkflow", "dummyTurnWorkflow", "codexAppServerTurnWorkflow", "roomAgentSupervisorWorkflow",
  "roomAgentActionWorkflow", "memoryMaintenanceWorkflow", "memoryConsolidationWorkflow", "memoryMutationWorkflow"
];
/**
 * Hash the exact UTF-8 fixture text, including formatting, for immutable manifest checks.
 */
export const sha256 = (value: string) => createHash("sha256").update(value).digest("hex");
export interface FixtureEntry {
  file: string; workflowId: string; workflowType: string; scenario: string;
  legacy: boolean; sha256: string;
}
/**
 * Serialize a protobuf history as formatted JSON with enums and 64-bit integers encoded as strings.
 * Byte arrays use base64 strings, and the fixture text ends with a newline.
 */
export function serializeHistory(value: CapturedHistory["history"]) {
  return JSON.stringify(temporal.api.history.v1.History.toObject(temporal.api.history.v1.History.create(value), {
    longs: String, enums: String, bytes: String
  }), null, 2) + "\n";
}

// Only synthetic server histories generated by our scenarios belong here.
// No production exports, arbitrary operator histories, paths or credentials.
/**
 * Validate this fixture format, supported decoded payloads and synthetic identity allowlist.
 * Reject known credential/path patterns; these bounded checks are not a universal privacy guarantee.
 */
export function assertSyntheticHistory(text: string) {
  const forbidden = /(?:C:\\\\Users\\\\|C:\/Users\/|\/home\/|\/Users\/|Bearer\s|\b(?:sk-|ghp_|gho_)[a-z0-9]+|-----BEGIN.*PRIVATE KEY|[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,})/i;
  const safeString = (value: string) => assert.ok(!forbidden.test(value), "History contains non-synthetic identity, path or credential material");
  safeString(text);
  const raw = JSON.parse(text);
  /**
   * Recursively inspect supported payload metadata, decoded JSON and nested fixture fields.
   * Reject unsupported encodings, credential keys and identities outside the synthetic allowlist.
   */
  function inspect(value: any): void {
    if (typeof value === "string") { safeString(value); return; }
    if (!value || typeof value !== "object") return;
    if (value.metadata?.encoding) {
      assert.ok(Object.keys(value.metadata).every(key => ["encoding", "type"].includes(key)), "Unexpected synthetic converter metadata");
      const encoding = Buffer.from(value.metadata.encoding, "base64").toString("utf8");
      assert.ok(["json/plain", "binary/null"].includes(encoding), `Unsupported synthetic payload encoding ${encoding}`);
      if (value.metadata.type) {
        // Temporal's patched() command writes its own KeywordList search
        // attribute using the default JSON converter plus encoded type metadata.
        assert.equal(encoding, "json/plain");
        assert.equal(Buffer.from(value.metadata.type, "base64").toString("utf8"), "KeywordList");
      }
      if (encoding === "json/plain") {
        assert.equal(typeof value.data, "string");
        const decoded = Buffer.from(value.data, "base64").toString("utf8");
        safeString(decoded); inspect(JSON.parse(decoded));
      } else assert.ok(!value.data, "Null payload must not carry data");
      return;
    }
    for (const [key, item] of Object.entries(value)) {
      assert.ok(!/^(?:password|apiKey|accessToken|refreshToken|authorization|secret)$/i.test(key), "Credentials do not belong in synthetic fixtures");
      if (key === "identity") assert.ok(["spaceapp-workflow-test-client", "spaceapp-workflow-test-worker"].includes(String(item)), "Unexpected non-synthetic identity");
      inspect(item);
    }
  }
  inspect(raw);
  return temporal.api.history.v1.History.fromObject(raw);
}

/**
 * Require the actual legacy settlement activity and reject current continuation activities or marker.
 * This checks the continuation patch branch, not every historical patch in the workflow.
 */
export function assertPrePatchSupervisor(history: CapturedHistory["history"]) {
  const activities = history.events?.flatMap(event => event.activityTaskScheduledEventAttributes?.activityType?.name ?? []) ?? [];
  assert.ok(activities.includes("settleRoomAgentBackgroundMission"), "Pre-patch fixture must exercise the actual legacy boolean activity");
  assert.ok(!activities.some(name => ["prepareRoomAgentBackgroundContinuation", "checkRoomAgentSupervisorTurn"].includes(name)), "Pre-patch fixture cannot use current supervisor activities");
  for (const event of history.events ?? []) for (const payloads of Object.values(event.markerRecordedEventAttributes?.details ?? {})) {
    for (const payload of payloads.payloads ?? []) {
      const decoded = Buffer.from(payload.data ?? []).toString("utf8");
      assert.ok(!decoded.includes("room-background-continuation-v1"), "Pre-patch fixture cannot contain the continuation patch marker");
    }
  }
}

/**
 * Load every committed history once and verify manifest coverage, identities and exact checksums.
 * Validate synthetic payloads and genuine legacy supervisor provenance before returning replay inputs.
 */
export async function loadHistoryFixtures() {
  const manifestText = await readFile(`${fixtureDirectory}/manifest.json`, "utf8");
  const manifest = JSON.parse(manifestText) as { schemaVersion: number; sdkVersion: string; sourceCommit: string; histories: FixtureEntry[] };
  assert.equal(manifest.schemaVersion, 1); assert.equal(manifest.sdkVersion, "1.24.0");
  assert.match(manifest.sourceCommit, /^[a-f0-9]{40}$/);
  assert.ok(manifest.histories.length >= 9, "Need all eight workflows plus pre-patch supervisor");
  assert.deepEqual([...new Set(manifest.histories.map(item => item.workflowType))].sort(), [...workflowTypes].sort());
  assert.ok(manifest.histories.some(item => item.workflowType === "roomAgentSupervisorWorkflow" && item.legacy));
  assert.ok(manifest.histories.some(item => item.workflowType === "roomAgentSupervisorWorkflow" && !item.legacy));
  const jsonFiles = (await readdir(fixtureDirectory)).filter(name => name.endsWith(".json") && name !== "manifest.json").sort();
  assert.deepEqual(jsonFiles, manifest.histories.map(item => item.file).sort(), "Every committed history must be replayed exactly once");
  assert.equal(new Set(manifest.histories.map(item => item.file)).size, manifest.histories.length);
  assert.equal(new Set(manifest.histories.map(item => item.workflowId)).size, manifest.histories.length);
  const fixtures = [];
  for (const item of manifest.histories) {
    assert.match(item.file, /^[a-z0-9-]+\.json$/); assert.match(item.workflowId, /^(?:spaceapp-test-|space-room-action:)/);
    const text = await readFile(`${fixtureDirectory}/${item.file}`, "utf8");
    assert.equal(sha256(text), item.sha256, `History checksum: ${item.file}`);
    const history = assertSyntheticHistory(text);
    assert.equal(history.events?.[0]?.workflowExecutionStartedEventAttributes?.workflowType?.name, item.workflowType);
    if (item.legacy) {
      assert.equal(item.workflowType, "roomAgentSupervisorWorkflow");
      assertPrePatchSupervisor(history);
    }
    fixtures.push({ ...item, history });
  }
  return fixtures;
}
